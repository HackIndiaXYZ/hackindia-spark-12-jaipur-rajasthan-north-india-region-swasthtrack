#!/usr/bin/env node
/**
 * Regenerates the three Supabase Auth e-mail templates in supabase/email-templates/
 * from the same source as the app's own mail (src/lib/email/templates/auth.ts), so the
 * login-code mails and the alert/report mails can never drift apart.
 *
 *   node scripts/build-auth-email-templates.mjs
 *
 * Then paste each file into Supabase → Authentication → Email Templates (the subject
 * to use is written at the top of each file). The templates keep Supabase's variables
 * as they are: {{ .Token }}, {{ .Email }} and {{ .SiteURL }}. The logo and the footer
 * links are built from {{ .SiteURL }}, so set Authentication → URL Configuration → Site
 * URL to the public address of the app (it must serve /email/logo.png).
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = mkdtempSync(join(tmpdir(), "swasthtrack-auth-mail-"));

try {
  // Compile just what the auth templates need. tsc reports errors for the "@/" alias
  // imports it cannot resolve here; it still emits, and the one runtime alias is fixed below.
  try {
    execFileSync(
      "npx",
      [
        "tsc",
        "src/lib/email/templates/auth.ts",
        "src/lib/health-rules.ts",
        "--rootDir", "src",
        "--outDir", out,
        "--module", "commonjs",
        "--target", "es2020",
        "--moduleResolution", "node",
        "--skipLibCheck",
        "--types", "node",
      ],
      { cwd: root, stdio: "pipe" },
    );
  } catch {
    // expected: unresolved "@/..." type imports; output is still written
  }

  const formatJs = join(out, "lib/email/format.js");
  writeFileSync(formatJs, readFileSync(formatJs, "utf8").replace('require("@/lib/health-rules")', 'require("../health-rules")'));

  const require = createRequire(import.meta.url);
  const auth = require(join(out, "lib/email/templates/auth.js"));

  const vars = { code: "{{ .Token }}" };
  const opts = { base: "{{ .SiteURL }}", recipient: "{{ .Email }}" };
  const files = [
    ["confirm-signup.html", 'Supabase > Authentication > Email Templates > "Confirm signup"', auth.renderConfirmSignupEmail],
    ["magic-link.html", 'Supabase > Authentication > Email Templates > "Magic Link" (this is the "sign in with email code" email)', auth.renderSignInCodeEmail],
    ["reset-password.html", 'Supabase > Authentication > Email Templates > "Reset password"', auth.renderPasswordResetEmail],
  ];

  const dir = join(root, "supabase/email-templates");
  mkdirSync(dir, { recursive: true });
  for (const [name, where, render] of files) {
    const mail = render(vars, opts);
    const html = `<!--
  ${where}
  Recommended Subject: ${mail.subject}
  Needs Supabase variables: Token (6-digit code), Email, SiteURL. No link is used on purpose.
  GENERATED by scripts/build-auth-email-templates.mjs from src/lib/email/templates/auth.ts — edit that, not this file.
-->
${mail.html}
`;
    writeFileSync(join(dir, name), html);
    console.log(`wrote supabase/email-templates/${name}  (subject: ${mail.subject})`);
  }
} finally {
  rmSync(out, { recursive: true, force: true });
}
